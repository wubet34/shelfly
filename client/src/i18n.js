export function t(text) {
  if (typeof text !== 'string') return text
  let language = 'en'
  try { language = localStorage.getItem('shelfly-language') || 'en' } catch { /* Use English when storage is unavailable. */ }
  if (language !== 'am') return text
  const stockError = text.match(/^Insufficient stock for (.+)\. Only (\d+) in stock\.$/)
  if (stockError) return `${stockError[1]}: በክምችት ውስጥ ${stockError[2]} ብቻ አለ።`
  return amharic[text] || text
}
